func TestGenerateRejectsMalformedManifest(t *testing.T) {
	tests := []struct {
		name    string
		mutate  func([][]string) [][]string
		wantErr string
	}{
		{
			name: "malformed header",
			mutate: func(records [][]string) [][]string {
				records[0][0] = "position"
				return records
			},
			wantErr: "header",
		},
		{
			name: "wrong columns",
			mutate: func(records [][]string) [][]string {
				records[1] = records[1][:4]
				return records
			},
			wantErr: "record on line 2: wrong number of fields",
		},
		{
			name: "wrong count",
			mutate: func(records [][]string) [][]string {
				return records[:len(records)-1]
			},
			wantErr: "got 108 entries, want 109",
		},
		{
			name: "surrounding whitespace",
			mutate: func(records [][]string) [][]string {
				records[1][1] = " " + records[1][1]
				return records
			},
			wantErr: "surrounding whitespace",
		},
		{
			name: "duplicate Chinese",
			mutate: func(records [][]string) [][]string {
				records[2][1] = records[1][1]
				records[2][4] = records[2][0] + "_" + records[2][1] + ".webp"
				return records
			},
			wantErr: "duplicate Chinese",
		},
		{
			name: "duplicate English EqualFold",
			mutate: func(records [][]string) [][]string {
				records[1][2], records[1][3] = "AS", "wechat_as"
				records[2][2], records[2][3] = "Aſ", "wechat_a"
				return records
			},
			wantErr: "duplicate case-folded English",
		},
		{
			name: "duplicate shortcode",
			mutate: func(records [][]string) [][]string {
				records[1][2], records[1][3] = "A-B", "wechat_a_b"
				records[2][2], records[2][3] = "A B", "wechat_a_b"
				return records
			},
			wantErr: "duplicate shortcode",
		},
		{
			name: "duplicate filename",
			mutate: func(records [][]string) [][]string {
				records[2][4] = records[1][4]
				return records
			},
			wantErr: "duplicate filename",
		},
		{
			name: "cross-language collision",
			mutate: func(records [][]string) [][]string {
				records[1][1] = records[2][2]
				records[1][4] = records[1][0] + "_" + records[1][1] + ".webp"
				return records
			},
			wantErr: "cross-entry cross-language collision",
		},
		{
			name: "bad index",
			mutate: func(records [][]string) [][]string {
				records[1][0] = "999"
				records[1][4] = "999_" + records[1][1] + ".webp"
				return records
			},
			wantErr: "is not sequential index 001",
		},
		{
			name: "bad filename",
			mutate: func(records [][]string) [][]string {
				records[1][4] = "wrong.webp"
				return records
			},
			wantErr: "filename",
		},
		{
			name: "bad shortcode",
			mutate: func(records [][]string) [][]string {
				records[1][3] = "wechat_wrong"
				return records
			},
			wantErr: "shortcode",
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			records := test.mutate(validManifestRecords())
			_, err := generate(strings.NewReader(encodeCSV(t, records)))
			if err == nil {
				t.Fatalf("generate() error = nil, want error containing %q", test.wantErr)
			}
			if !strings.Contains(err.Error(), test.wantErr) {
				t.Fatalf("generate() error = %q, want error containing %q", err, test.wantErr)
			}
		})
	}
}

func TestGenerateOutputIsDeterministic(t *testing.T) {
	manifest := encodeCSV(t, validManifestRecords())
	first, err := generate(strings.NewReader(manifest))
	if err != nil {
		t.Fatal(err)
	}
	second, err := generate(strings.NewReader(manifest))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(first, second) {
		t.Fatal("generate() returned different output for identical input")
	}
	if !bytes.HasPrefix(first, []byte("// Code generated by go generate; DO NOT EDIT.\n\npackage textemoji\n")) {
		t.Fatalf("generated source has unexpected prefix: %q", first[:min(len(first), 80)])
	}
}

func validManifestRecords() [][]string {
	records := make([][]string, 1, entryCount+1)
	records[0] = []string{"index", "chinese", "english", "shortcode", "filename"}
	for index := 1; index <= entryCount; index++ {
		indexText := fmt.Sprintf("%03d", index)
		chinese := "中文" + indexText
		english := "Alias" + indexText
		records = append(records, []string{
			indexText,
			chinese,
			english,
			canonicalShortcode(english),
			indexText + "_" + chinese + ".webp",
		})
	}
	return records
}

func encodeCSV(t *testing.T, records [][]string) string {
	t.Helper()
	var output strings.Builder
	writer := csv.NewWriter(&output)
	if err := writer.WriteAll(records); err != nil {
		t.Fatal(err)
	}
	return output.String()
}
